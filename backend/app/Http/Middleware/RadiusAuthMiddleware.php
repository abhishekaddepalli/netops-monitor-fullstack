<?php

namespace App\Http\Middleware;

use App\Models\GlobalSetting;
use Closure;
use Illuminate\Http\Request;
use Symfony\Component\HttpFoundation\Response;

class RadiusAuthMiddleware
{
    /**
     * Handle an incoming request for Radius integration API.
     */
    public function handle(Request $request, Closure $next): Response
    {
        $radiusEnabled = GlobalSetting::getValue('radius_enabled', '1');
        if ($radiusEnabled === '0' || $radiusEnabled === false) {
            return response()->json([
                'success' => false,
                'error' => 'Radius Integration API is currently disabled by platform Super Admin.',
            ], 403);
        }

        $expectedKey = GlobalSetting::getValue('radius_api_key');
        if (! $expectedKey) {
            return response()->json([
                'success' => false,
                'error' => 'Radius API Key has not been generated by platform Super Admin. Visit Admin > Radius Integration to generate one.',
            ], 401);
        }

        // Check Authorization Bearer header, X-Radius-Key, or X-API-Key
        $providedKey = null;
        $authHeader = $request->header('Authorization');
        if ($authHeader && str_starts_with($authHeader, 'Bearer ')) {
            $providedKey = substr($authHeader, 7);
        } elseif ($request->header('X-Radius-Key')) {
            $providedKey = $request->header('X-Radius-Key');
        } elseif ($request->header('X-API-Key')) {
            $providedKey = $request->header('X-API-Key');
        } elseif ($request->query('api_key')) {
            $providedKey = $request->query('api_key');
        }

        if (! $providedKey || ! hash_equals($expectedKey, trim($providedKey))) {
            return response()->json([
                'success' => false,
                'error' => 'Unauthorized. Invalid or missing Radius API Key. Provide via "Authorization: Bearer <KEY>" or "X-Radius-Key: <KEY>" header.',
            ], 401);
        }

        return $next($request);
    }
}
